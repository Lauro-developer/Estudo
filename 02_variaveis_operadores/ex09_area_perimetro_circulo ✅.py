"""
Exercício: Peça o raio de um círculo e calcule a área e o perímetro (pi = 3.14159).
"""

# Escreva sua solução abaixo:

raio_circulo = float(input("Me diga o raio do circulo: "))
pi = 3.14159
area = pi * (raio_circulo * raio_circulo)
print(f"A area do circulo com o raio de {raio_circulo}cm é: {area}")